'use strict'

const fs = require('node:fs')
const path = require('node:path')

const repositoryRoot = path.resolve(__dirname, '..')
const themesDirectory = path.join(repositoryRoot, 'demo', 'themes')
const themeDirectory = path.join(themesDirectory, 'toybox')
const generatedMarker = path.join(themeDirectory, '.toybox-demo-copy')
const themeEntries = ['_config.yml', 'package.json', 'languages', 'layout', 'scripts', 'source']

fs.mkdirSync(themesDirectory, { recursive: true })

if (fs.existsSync(themeDirectory) || fs.lstatSync(themesDirectory).isSymbolicLink()) {
  const stat = fs.lstatSync(themeDirectory)
  if (stat.isSymbolicLink()) {
    fs.unlinkSync(themeDirectory)
  } else if (fs.existsSync(generatedMarker)) {
    fs.rmSync(themeDirectory, { recursive: true, force: true })
  } else {
    throw new Error('demo/themes/toybox exists and was not generated by the demo builder')
  }
}

fs.mkdirSync(themeDirectory, { recursive: true })
themeEntries.forEach(entry => {
  fs.cpSync(path.join(repositoryRoot, entry), path.join(themeDirectory, entry), { recursive: true })
})
fs.writeFileSync(generatedMarker, 'Generated by tools/prepare-demo-theme.js\n')
